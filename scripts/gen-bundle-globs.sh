#!/bin/bash
# Writes crates/dustpan-core/src/protect/macos_bundles.rs from Mole's bundle-id protection lists.
#
#   scripts/gen-bundle-globs.sh [--check] [MOLE_CHECKOUT]
#
# Reads lib/core/app_protection_data.sh at MOLE_SHA from the Mole checkout (default ../mole) with
# `git show`, so the result does not depend on what that checkout has checked out. To take a newer
# Mole, change MOLE_SHA here and run the script again. --check exits 1 when the committed file
# differs from a fresh run.
set -euo pipefail

MOLE_SHA=5dd93fe34af53cc6e0885cfc10234156fbc6d562
SOURCE=lib/core/app_protection_data.sh
LISTS=(SYSTEM_CRITICAL_BUNDLES DATA_PROTECTED_BUNDLES)

check=false
if [[ "${1:-}" == "--check" ]]; then
    check=true
    shift
fi
repo=$(cd "$(dirname "$0")/.." && pwd)
mole=${1:-$repo/../mole}
out=$repo/crates/dustpan-core/src/protect/macos_bundles.rs

data=$(git -C "$mole" show "$MOLE_SHA:$SOURCE")

# The entries of one `readonly NAME=( ... )` array, one per line, in file order.
entries() {
    awk -v open="readonly $1=(" '
        index($0, open) == 1 { inside = 1; next }
        inside && /^\)/ { exit }
        inside && match($0, /^[[:space:]]*"[^"]+"/) {
            entry = substr($0, RSTART, RLENGTH)
            sub(/^[[:space:]]*"/, "", entry)
            sub(/"$/, "", entry)
            print entry
        }
    ' <<< "$data"
}

# The matcher knows the star only.
validate() {
    case "$2" in
        *\?* | *\[* | *\]* | *\|* | *\(* | *\)* | *\\*)
            echo "$1: unsupported pattern syntax: $2" >&2
            return 1
            ;;
    esac
}

generate() {
    local list entry count
    echo "//! Generated by scripts/gen-bundle-globs.sh from Mole $MOLE_SHA,"
    echo "//! $SOURCE. Do not edit: change the script's MOLE_SHA and run it again."
    for list in "${LISTS[@]}"; do
        count=0
        echo
        echo "pub(super) static $list: &[&str] = &["
        while IFS= read -r entry; do
            validate "$list" "$entry" || return 1
            echo "    \"$entry\","
            count=$((count + 1))
        done < <(entries "$list")
        if [[ $count -eq 0 ]]; then
            echo "$list: no entries found in $SOURCE at $MOLE_SHA" >&2
            return 1
        fi
        echo "];"
    done
}
generated=$(generate) || exit 1

if $check; then
    if ! diff -u "$out" <(printf '%s\n' "$generated"); then
        echo "macos_bundles.rs is stale: run scripts/gen-bundle-globs.sh" >&2
        exit 1
    fi
    echo "macos_bundles.rs matches Mole $MOLE_SHA"
else
    printf '%s\n' "$generated" > "$out"
    echo "wrote $out from Mole $MOLE_SHA"
fi
